import fs from 'node:fs';
import assert from 'node:assert/strict';
const read = path => fs.readFileSync(new URL('../' + path, import.meta.url), 'utf8');
const json = path => JSON.parse(read(path));
const version = json('package.json').version;
assert.equal(json('package-lock.json').version, version);
assert.equal(json('package-lock.json').packages[''].version, version);
assert.equal(json('update.json').version, version);
const pubspec = read('flutter_app/pubspec.yaml').match(/^version:\s*(\S+)\+(\d+)/m);
assert.equal(pubspec[1], version);
const android = read('android/app/build.gradle');
assert.equal(android.match(/versionName\s+"([^"]+)"/)[1], version);
assert.equal(android.match(/versionCode\s+(\d+)/)[1], pubspec[2]);
assert.match(read('client/version.js'), new RegExp('"' + version.replaceAll('.', '\\.') + '"'));
assert.equal(read('flutter_app/lib/data/app_update.dart').match(/const appVersion = '([^']+)'/)[1], version);
assert.equal(read('flutter_app/lib/domain/library_backup.dart').match(/'appVersion': '([^']+)'/)[1], version);
if (process.env.GITHUB_REF?.startsWith('refs/tags/')) assert.equal(process.env.GITHUB_REF, 'refs/tags/v' + version);
assert.equal(fs.existsSync(new URL('../README.md', import.meta.url)), false, 'Root README must remain absent');
console.log('Release metadata consistent: v' + version + ' (' + pubspec[2] + ')');
